"use server";

import { safeRevalidatePath } from "@/shared/utils/cache";
import { repository } from "@/shared/db/supabase";
import { generateEventPlanWithAI } from "../infrastructure/gemini.client";
import { EventPlan } from "../domain/plan.schema";
import { fromMajorUnits } from "@/shared/types/money";
import { ok, err, Result } from "@/shared/types/result";

export async function generatePlanAction(eventId: string): Promise<Result<{ plan: EventPlan; provider: string }>> {
  try {
    const event = repository.getEventById(eventId);
    if (!event) return err("Event not found");

    const result = await generateEventPlanWithAI(event);
    return ok(result);
  } catch (error: any) {
    console.error("AI Plan Generation failed:", error);
    return err(error.message || "Failed to generate AI plan.");
  }
}

export async function commitPlanToEventAction(eventId: string, plan: EventPlan): Promise<Result<{ tasksCreated: number }>> {
  try {
    const event = repository.getEventById(eventId);
    if (!event) return err("Event not found");

    const eventDate = new Date(event.event_date);

    // 1. Map and create tasks with calculated due dates
    const createdTaskMap = new Map<string, string>(); // title -> taskId
    let tasksCreated = 0;

    for (const pTask of plan.proposedTasks) {
      const taskDueDate = new Date(eventDate);
      taskDueDate.setDate(taskDueDate.getDate() - pTask.daysBeforeEvent);

      const taskStartDate = new Date(taskDueDate);
      taskStartDate.setDate(taskStartDate.getDate() - pTask.estimatedDays);

      const created = repository.createTask({
        event_id: eventId,
        title: pTask.title,
        description: `Generated by AI Planning Engine. Category: ${pTask.category}`,
        category: pTask.category,
        priority: pTask.priority,
        status: pTask.prerequisiteTitles && pTask.prerequisiteTitles.length > 0 ? "BLOCKED" : "READY",
        start_date: taskStartDate.toISOString().split("T")[0],
        due_date: taskDueDate.toISOString().split("T")[0],
        estimated_days: pTask.estimatedDays,
      });

      createdTaskMap.set(pTask.title, created.id);
      tasksCreated++;
    }

    // 2. Wire task dependencies
    for (const pTask of plan.proposedTasks) {
      const currentTaskId = createdTaskMap.get(pTask.title);
      if (!currentTaskId || !pTask.prerequisiteTitles) continue;

      for (const prereqTitle of pTask.prerequisiteTitles) {
        const prereqTaskId = createdTaskMap.get(prereqTitle);
        if (prereqTaskId) {
          repository.createDependency(currentTaskId, prereqTaskId);
        }
      }
    }

    safeRevalidatePath(`/events/${eventId}`);
    safeRevalidatePath(`/events/${eventId}/timeline`);
    safeRevalidatePath(`/events/${eventId}/budget`);

    return ok({ tasksCreated });
  } catch (error: any) {
    console.error("Failed to commit AI plan:", error);
    return err(error.message || "Failed to commit AI plan to event.");
  }
}
